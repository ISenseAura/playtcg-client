export function foldAttackName(name: string): string {
	const folded = String(name || '').normalize('NFKD').toLowerCase();
	let words = '';
	let cur = '';
	for (let i = 0; i < folded.length; i++) {
		const code = folded.charCodeAt(i);
		if (code >= 0x300 && code <= 0x36f) continue;
		const ch = folded.charAt(i);
		if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) {
			cur += ch;
		} else if (cur) {
			words += (words ? ' ' : '') + cur;
			cur = '';
		}
	}
	if (cur) words += (words ? ' ' : '') + cur;
	return words || String(name || '').trim().toLowerCase();
}

const attackHitByFold: { [name: string]: AttackHitStyle } = {};
for (const name in ATTACK_HIT) {
	attackHitByFold[foldAttackName(name)] = ATTACK_HIT[name];
}

export function lookupAttackHit(name: string): AttackHitStyle | undefined {
	if (!name) return undefined;
	return attackHitByFold[foldAttackName(name)];
}
